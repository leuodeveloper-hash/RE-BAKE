const CERTS = ['pastry_written', 'baking_written'];
const PRACTICAL_CERTS = ['pastry_practical', 'baking_practical'];

async function main() {
  // 1) 기존 전체 삭제
  const old = await db.collection('exam_schedules').get();
  console.log(`기존 ${old.size}개 삭제 중...`);
  const delBatch = db.batch();
  old.docs.forEach(d => delBatch.delete(d.ref));
  await delBatch.commit();

  // 2) 재생성 (제과·제빵 × 41회차)
  let count = 0;
  const batch = db.batch();
  // 필기 (원서접수 기간 + 필기 기간, 발표=시험종료 즉시)
  for (const cert of CERTS) {
    for (const [round, regS, , exS, exE] of ROUNDS) {
      const id = `${cert}_2026_${round}`;
      batch.set(db.collection('exam_schedules').doc(id), {
        examType: cert,
        round: `2026년 ${round}회`,
        registrationStart: iso(regS, 10),
        examDate: iso(exS),          // 필기 시작
        examEndDate: iso(exE),        // 필기 종료 (기간)
        resultDate: iso(exE),         // 시험종료 즉시 발표
      });
      count++;
    }
  }
  // 실기 (원서접수 + 실기 기간 + 합격자발표)
  for (const cert of PRACTICAL_CERTS) {
    for (const [round, regS, , exS, exE, res] of PRACTICAL_ROUNDS) {
      const id = `${cert}_2026_${round}`;
      batch.set(db.collection('exam_schedules').doc(id), {
        examType: cert,
        round: `2026년 ${round}회`,
        registrationStart: iso(regS, 10),
        examDate: iso(exS),          // 실기 시작
        examEndDate: iso(exE),        // 실기 종료 (기간)
        resultDate: iso(res),         // 합격자 발표일
      });
      count++;
    }
  }
  await batch.commit();
  console.log(`완료: ${count}개 생성 (필기 ${ROUNDS.length}회 + 실기 ${PRACTICAL_ROUNDS.length}회, 각 제과·제빵)`);
  process.exit(0);
}
main();
